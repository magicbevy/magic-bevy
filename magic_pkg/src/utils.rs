pub fn get_workspace_engine_version(workspace_root: &Path) -> Option<String> {
    let cargo_path = workspace_root.join("Cargo.toml");
    let content = fs::read_to_string(cargo_path).ok()?;
    let value: toml::Value = toml::from_str(&content).ok()?;

    value
        .get("package")
        .and_then(|pkg| pkg.get("version"))
        .and_then(|v| v.as_str())
        .map(String::from)
}

pub struct OutdatedInfo {
    pub id: String,
    pub current_version: String,
    pub latest_version: String,
}

pub fn print_packages_table(packages: &[crate::manifest::PackageManifest]) {
    let mut cat_w = 8;
    let mut id_w = 12;
    let mut ver_w = 7;
    let mut stat_w = 8;
    let mut targ_w = 10;

    for p in packages {
        cat_w = cat_w.max(p.category.len());
        id_w = id_w.max(p.id().len());
        ver_w = ver_w.max(p.version.len());
        let status_str = if p.enabled { "Enabled" } else { "Disabled" };
        stat_w = stat_w.max(status_str.len());

        let targets_str = p
            .targets
            .iter()
            .map(|t| match t {
                crate::manifest::PackageTarget::Editor => "Editor",
                crate::manifest::PackageTarget::Runtime => "Runtime",
            })
            .collect::<Vec<_>>()
            .join(", ");
        targ_w = targ_w.max(targets_str.len());
    }

    cat_w += 2;
    id_w += 2;
    ver_w += 2;
    stat_w += 2;
    targ_w += 2;

    let top = format!(
        "┌{}┬{}┬{}┬{}┬{}┐",
        "─".repeat(cat_w),
        "─".repeat(id_w),
        "─".repeat(ver_w),
        "─".repeat(stat_w),
        "─".repeat(targ_w)
    );
    let header = format!(
        "│ {:<cat_len$} │ {:<id_len$} │ {:<ver_len$} │ {:<stat_len$} │ {:<targ_len$} │",
        "Category",
        "Package ID",
        "Version",
        "Status",
        "Targets",
        cat_len = cat_w - 2,
        id_len = id_w - 2,
        ver_len = ver_w - 2,
        stat_len = stat_w - 2,
        targ_len = targ_w - 2
    );
    let sep = format!(
        "├{}┼{}┼{}┼{}┼{}┤",
        "─".repeat(cat_w),
        "─".repeat(id_w),
        "─".repeat(ver_w),
        "─".repeat(stat_w),
        "─".repeat(targ_w)
    );
    let bot = format!(
        "└{}┴{}┴{}┴{}┴{}┘",
        "─".repeat(cat_w),
        "─".repeat(id_w),
        "─".repeat(ver_w),
        "─".repeat(stat_w),
        "─".repeat(targ_w)
    );

    println!("    {top}");
    println!("    {header}");
    println!("    {sep}");
    for p in packages {
        let status_str = if p.enabled { "Enabled" } else { "Disabled" };
        let targets_str = p
            .targets
            .iter()
            .map(|t| match t {
                crate::manifest::PackageTarget::Editor => "Editor",
                crate::manifest::PackageTarget::Runtime => "Runtime",
            })
            .collect::<Vec<_>>()
            .join(", ");

        println!(
            "    │ {:<cat_len$} │ {:<id_len$} │ {:<ver_len$} │ {:<stat_len$} │ {:<targ_len$} │",
            p.category,
            p.id(),
            p.version,
            status_str,
            targets_str,
            cat_len = cat_w - 2,
            id_len = id_w - 2,
            ver_len = ver_w - 2,
            stat_len = stat_w - 2,
            targ_len = targ_w - 2
        );
    }
    println!("    {bot}");
}

