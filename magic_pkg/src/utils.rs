pub const AUTO_HEADER: &str = "# Auto-generated by magic_pkg. Do not edit manually.";
pub const AUTO_RS_HEADER: &str = "// Auto-generated by magic_pkg. Do not edit manually.";

pub fn extract_zip_archive(zip_path: &Path, target_dir: &Path) -> Result<(), PackageError> {
    let file = fs::File::open(zip_path).map_err(|source| PackageError::Io {
        path: zip_path.to_path_buf(),
        source,
    })?;
    let mut archive =
        zip::ZipArchive::new(file).map_err(|e| PackageError::ZipError(e.to_string()))?;

    for i in 0..archive.len() {
        let mut file = archive
            .by_index(i)
            .map_err(|e| PackageError::ZipError(e.to_string()))?;
        let outpath = match file.enclosed_name() {
            Some(path) => target_dir.join(path),
            None => continue,
        };

        if file.name().ends_with('/') {
            fs::create_dir_all(&outpath).map_err(|source| PackageError::Io {
                path: outpath.clone(),
                source,
            })?;
        } else {
            if let Some(p) = outpath.parent() {
                if !p.exists() {
                    fs::create_dir_all(p).map_err(|source| PackageError::Io {
                        path: p.to_path_buf(),
                        source,
                    })?;
                }
            }
            let mut outfile = fs::File::create(&outpath).map_err(|source| PackageError::Io {
                path: outpath.clone(),
                source,
            })?;
            io::copy(&mut file, &mut outfile).map_err(|source| PackageError::Io {
                path: outpath,
                source,
            })?;
        }
    }
    Ok(())
}

pub fn copy_dir_all(src: impl AsRef<Path>, dst: impl AsRef<Path>) -> Result<(), PackageError> {
    fs::create_dir_all(&dst).map_err(|s| PackageError::Io {
        path: dst.as_ref().to_path_buf(),
        source: s,
    })?;
    for entry in fs::read_dir(src).map_err(|s| PackageError::Io {
        path: dst.as_ref().to_path_buf(),
        source: s,
    })? {
        let entry = entry.map_err(|s| PackageError::Io {
            path: dst.as_ref().to_path_buf(),
            source: s,
        })?;
        let ty = entry.file_type().map_err(|s| PackageError::Io {
            path: entry.path(),
            source: s,
        })?;
        if ty.is_dir() {
            copy_dir_all(entry.path(), dst.as_ref().join(entry.file_name()))?;
        } else {
            fs::copy(entry.path(), dst.as_ref().join(entry.file_name())).map_err(|s| {
                PackageError::Io {
                    path: entry.path(),
                    source: s,
                }
            })?;
        }
    }
    Ok(())
}

pub fn uuid_lite() -> String {
    use std::time::{SystemTime, UNIX_EPOCH};
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_nanos())
        .unwrap_or(0);
    format!("{:x}", nanos)
}

pub fn find_workspace_root(start_dir: &Path) -> PathBuf {
    let mut current = start_dir.to_path_buf();
    loop {
        let manifest = current.join("Cargo.toml");
        if manifest.is_file() {
            if let Ok(content) = fs::read_to_string(&manifest) {
                if content.contains("[workspace]") {
                    return current;
                }
            }
        }
        if !current.pop() {
            break;
        }
    }
    start_dir.to_path_buf()
}

pub fn find_crate_manifest(workspace_root: &Path, crate_name: &str) -> Option<PathBuf> {
    let short_name = crate_name.trim_start_matches("magic_pkg_");

    let candidates = [
        workspace_root
            .join(format!("magic_{short_name}"))
            .join(crate_name)
            .join("Cargo.toml"),
        workspace_root
            .join(format!("magic_{short_name}"))
            .join("Cargo.toml"),
        workspace_root.join(crate_name).join("Cargo.toml"),
        workspace_root.join(short_name).join("Cargo.toml"),
        workspace_root
            .join("crates")
            .join(crate_name)
            .join("Cargo.toml"),
        workspace_root
            .join("crates")
            .join(short_name)
            .join("Cargo.toml"),
    ];

    for candidate in &candidates {
        if candidate.is_file() {
            if let Ok(name) = package_name(candidate) {
                if name == crate_name {
                    return Some(candidate.clone());
                }
            }
        }
    }

    fn walk(dir: &Path, crate_name: &str, depth: usize) -> Option<PathBuf> {
        if depth > 3 {
            return None;
        }
        if let Ok(entries) = fs::read_dir(dir) {
            for entry in entries.filter_map(Result::ok) {
                let path = entry.path();
                if path.is_dir() {
                    let folder_name = path.file_name().unwrap_or_default().to_string_lossy();
                    if folder_name.starts_with('.')
                        || folder_name == "target"
                        || folder_name == "packages"
                    {
                        continue;
                    }
                    let manifest = path.join("Cargo.toml");
                    if manifest.is_file() {
                        if let Ok(name) = package_name(&manifest) {
                            if name == crate_name {
                                return Some(manifest);
                            }
                        }
                    }
                    if let Some(found) = walk(&path, crate_name, depth + 1) {
                        return Some(found);
                    }
                }
            }
        }
        None
    }

    walk(workspace_root, crate_name, 1)
}

pub fn update_manifest_dependencies(
    manifest_path: &Path,
    dependencies: &[(String, String, PathBuf)],
) -> Result<bool, PackageError> {
    let content = fs::read_to_string(manifest_path).map_err(|source| PackageError::Io {
        path: manifest_path.to_path_buf(),
        source,
    })?;

    let manifest_dir = manifest_path.parent().unwrap_or_else(|| Path::new("."));

    let lines: Vec<&str> = content
        .lines()
        .filter(|line| line.trim() != AUTO_HEADER)
        .collect();

    let mut new_lines: Vec<String> = Vec::new();
    let mut in_dependencies = false;
    let mut dependencies_found = false;

    for line in lines {
        let trimmed = line.trim();
        if trimmed.starts_with('[') {
            if trimmed == "[dependencies]" {
                in_dependencies = true;
                dependencies_found = true;
                new_lines.push(line.to_string());
                for (alias, crate_name, crate_path) in dependencies {
                    let rel_path = relative_path(manifest_dir, crate_path);
                    let path_str = toml_path(&rel_path);
                    new_lines.push(format!(
                        "{alias} = {{ package = \"{crate_name}\", path = \"{path_str}\" }}"
                    ));
                }
                continue;
            } else {
                in_dependencies = false;
            }
        }

        if in_dependencies {
            if trimmed.starts_with("package_")
                || trimmed == "# BEGIN MAGIC_PKG DEPENDENCIES"
                || trimmed == "# END MAGIC_PKG DEPENDENCIES"
            {
                continue;
            }
        } else if trimmed == "# BEGIN MAGIC_PKG DEPENDENCIES"
            || trimmed == "# END MAGIC_PKG DEPENDENCIES"
        {
            continue;
        }

        new_lines.push(line.to_string());
    }

    if !dependencies_found {
        if !new_lines.is_empty() && !new_lines.last().unwrap().is_empty() {
            new_lines.push(String::new());
        }
        new_lines.push("[dependencies]".to_string());
        for (alias, crate_name, crate_path) in dependencies {
            let rel_path = relative_path(manifest_dir, crate_path);
            let path_str = toml_path(&rel_path);
            new_lines.push(format!(
                "{alias} = {{ package = \"{crate_name}\", path = \"{path_str}\" }}"
            ));
        }
    }

    let updated_content = format!("{AUTO_HEADER}\n{}\n", new_lines.join("\n"));

    if updated_content == content {
        Ok(false)
    } else {
        fs::write(manifest_path, updated_content).map_err(|source| PackageError::Io {
            path: manifest_path.to_path_buf(),
            source,
        })?;
        Ok(true)
    }
}

pub fn validate_segment(kind: &str, value: &str) -> Result<(), PackageError> {
    if value.is_empty()
        || !value.chars().all(|character| {
            character.is_ascii_alphanumeric() || character == '_' || character == '-'
        })
    {
        return Err(PackageError::InvalidArgument(format!(
            "{kind} must use only ASCII letters, digits, '_' or '-'"
        )));
    }
    Ok(())
}

pub fn package_name(manifest_path: &Path) -> Result<String, PackageError> {
    let contents = fs::read_to_string(manifest_path).map_err(|source| PackageError::Io {
        path: manifest_path.to_path_buf(),
        source,
    })?;
    let mut in_package_table = false;
    for raw_line in contents.lines() {
        let line = raw_line.trim();
        if line.starts_with('[') {
            in_package_table = line == "[package]";
            continue;
        }
        if !in_package_table {
            continue;
        }
        let Some((key, value)) = line.split_once('=') else {
            continue;
        };
        if key.trim() != "name" {
            continue;
        }
        let value = value.trim();
        let name = match value.chars().next() {
            Some('"') => value[1..].split('"').next(),
            Some('\'') => value[1..].split('\'').next(),
            _ => None,
        };
        if let Some(name) = name.filter(|name| !name.trim().is_empty()) {
            return Ok(name.to_owned());
        }
    }
    Err(PackageError::InvalidManifest {
        path: manifest_path.to_path_buf(),
        message: "Cargo.toml requires a non-empty package.name".into(),
    })
}

pub fn read_directories(path: &Path) -> Result<Vec<PathBuf>, PackageError> {
    let entries = fs::read_dir(path).map_err(|source| PackageError::Io {
        path: path.to_path_buf(),
        source,
    })?;
    Ok(entries
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .filter(|path| path.is_dir())
        .collect())
}

pub fn file_name(path: &Path) -> Result<String, PackageError> {
    path.file_name()
        .and_then(|name| name.to_str())
        .map(str::to_owned)
        .ok_or_else(|| PackageError::InvalidManifest {
            path: path.to_path_buf(),
            message: "path must have a valid UTF-8 name".into(),
        })
}

pub fn cargo_identifier(input: &str) -> String {
    let identifier: String = input
        .chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() {
                character.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect();
    let identifier = identifier.trim_matches('_');
    if identifier.is_empty() {
        "package".into()
    } else {
        identifier.into()
    }
}

pub fn relative_path(from: &Path, to: &Path) -> PathBuf {
    let from = from.components().collect::<Vec<_>>();
    let to = to.components().collect::<Vec<_>>();
    let common = from
        .iter()
        .zip(&to)
        .take_while(|(left, right)| left == right)
        .count();
    let mut result = PathBuf::new();
    for _ in common..from.len() {
        result.push("..");
    }
    for component in &to[common..] {
        result.push(component.as_os_str());
    }
    result
}

pub fn toml_path(path: &Path) -> String {
    path.to_string_lossy().replace('\\', "/")
}

pub fn update_editor_lib_register(
    lib_path: &Path,
    aliases: &[String],
) -> Result<bool, PackageError> {
    if let Some(parent) = lib_path.parent() {
        let _ = fs::create_dir_all(parent);
    }

    let mut body = String::new();
    body.push_str(&format!("{AUTO_RS_HEADER}\n\n"));
    body.push_str("use magic_core::EditorRegistry;\n");
    body.push_str("pub fn register_all_packages(_registry: &mut EditorRegistry) {\n");

    for alias in aliases {
        body.push_str(&format!("    {alias}::register(_registry);\n"));
    }

    body.push_str("}\n");

    let current = fs::read_to_string(lib_path).unwrap_or_default();
    if current == body {
        Ok(false)
    } else {
        fs::write(lib_path, body).map_err(|source| PackageError::Io {
            path: lib_path.to_path_buf(),
            source,
        })?;
        Ok(true)
    }
}

